-- Replace broad authenticated CMS access with approved-admin access.
drop policy if exists "Authenticated manage clinic schedule" on public.clinic_schedule;
drop policy if exists "Authenticated manage clinic reviews" on public.clinic_reviews;
drop policy if exists "Authenticated manage clinic news" on public.clinic_news;
drop policy if exists "Admins manage clinic schedule" on public.clinic_schedule;
create policy "Admins manage clinic schedule" on public.clinic_schedule for all to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "Admins manage clinic reviews" on public.clinic_reviews;
create policy "Admins manage clinic reviews" on public.clinic_reviews for all to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "Admins manage clinic news" on public.clinic_news;
create policy "Admins manage clinic news" on public.clinic_news for all to authenticated using(public.is_admin()) with check(public.is_admin());

-- Tighten public review/news reads to exclude Trash.

insert into storage.buckets(id,name,public) values('cms-media','cms-media',true) on conflict(id) do update set public=true;
drop policy if exists "Public read Encita CMS media" on storage.objects;
create policy "Public read Encita CMS media" on storage.objects for select to public using(bucket_id='cms-media');
drop policy if exists "Admins insert Encita CMS media" on storage.objects;
create policy "Admins insert Encita CMS media" on storage.objects for insert to authenticated with check(bucket_id='cms-media' and public.is_admin());
drop policy if exists "Admins update Encita CMS media" on storage.objects;
